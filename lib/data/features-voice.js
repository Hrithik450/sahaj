function pickLines(language, table) {
  return table[language] ?? table.en;
}

function buildGovernmentFeatureLines(language) {
  const lang = GOVERNMENT_FEATURES_VOICE[language] ? language : "en";
  const features = GOVERNMENT_FEATURES_VOICE[lang];
  const ordinals = ORDINALS[lang] ?? ORDINALS.en;

  return features.map((feature, index) => {
    const ordinal = ordinals[index] ?? String(index + 1);
    return `${ordinal}. ${feature.title}. ${feature.description}`;
  });
}

export function governmentFeaturesVoiceLines(language = "en") {
  const lang = GOVERNMENT_FEATURES_VOICE[language] ? language : "en";

  return [
    pickLines(lang, FEATURES_SECTION_LABEL),
    pickLines(lang, FEATURES_SECTION_TITLE),
    pickLines(lang, GOVERNMENT_INTRO),
    ...buildGovernmentFeatureLines(lang),
    pickLines(lang, GOVERNMENT_OUTRO),
  ];
}

export function governmentFeaturesVoiceCaption(language = "en") {
  return governmentFeaturesVoiceLines(language).join(" ");
}

export function governmentFeaturesVoicePrompt(language = "en") {
  const lang = GOVERNMENT_FEATURES_VOICE[language] ? language : "en";
  const style = TTS_STYLE[lang] ?? TTS_STYLE.en;
  const body = governmentFeaturesVoiceCaption(lang);
  return `${style}\n\n${body}`;
}

export function governmentFeaturesVoiceAudioPath(language = "en") {
  const lang = GOVERNMENT_FEATURES_VOICE[language] ? language : "en";
  return `/audio/features/government-${lang}.wav`;
}
